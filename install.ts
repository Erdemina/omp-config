#!/usr/bin/env bun
/**
 * Install or roll back this OMP configuration.
 *
 *   ./install.ts --profile claude|codex [--dry-run]
 *   ./install.ts --restore <backup-dir>
 *
 * Writes only config.yml, AGENTS.md and profiles/*.yml under
 * ${PI_CODING_AGENT_DIR:-~/.omp/agent}. Authentication, sessions and databases
 * are never touched. Every replaced or removed file is backed up first, and
 * settings this repository does not manage are kept from the existing config.yml.
 */
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync, copyFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";

const ROOT = import.meta.dir;
const PROFILES = ["claude", "codex"] as const;
type Profile = (typeof PROFILES)[number];

/** Keys the previous version of this repo set and this one deliberately leaves to omp defaults. */
const RETIRED_KEYS = [
	"compaction.thresholdTokens",
	"compaction.idleEnabled",
	"compaction.idleThresholdTokens",
	"compaction.idleTimeoutSeconds",
	"task.maxRuntimeMs",
	"task.softRequestBudget",
	"task.agentModelOverrides",
];
/** Files the previous version installed; removed (after backup) because they no longer exist here. */
const RETIRED_FILES = ["agents/opus.md", "agents/gpt6.md", "extensions/orchestrator.ts"];
/** Settings replaced as a whole rather than merged key by key. */
const REPLACED_RECORDS = new Set(["modelRoles", "modelTags"]);

type Tree = Record<string, unknown>;
const isTree = (v: unknown): v is Tree => typeof v === "object" && v !== null && !Array.isArray(v);

function readYaml(path: string): Tree {
	if (!existsSync(path)) return {};
	const parsed = Bun.YAML.parse(readFileSync(path, "utf8"));
	if (parsed == null) return {};
	if (!isTree(parsed)) throw new Error(`${path}: expected a YAML mapping`);
	return parsed;
}

/** `over` wins; nested mappings merge unless listed in REPLACED_RECORDS. */
export function merge(base: Tree, over: Tree, path = ""): Tree {
	const out: Tree = { ...base };
	for (const [key, value] of Object.entries(over)) {
		const id = path ? `${path}.${key}` : key;
		out[key] = isTree(value) && isTree(out[key]) && !REPLACED_RECORDS.has(id) ? merge(out[key] as Tree, value, id) : value;
	}
	return out;
}

function deletePath(tree: Tree, id: string): void {
	const parts = id.split(".");
	const parents: Tree[] = [tree];
	for (const part of parts.slice(0, -1)) {
		const next = parents.at(-1)![part];
		if (!isTree(next)) return;
		parents.push(next);
	}
	delete parents.at(-1)![parts.at(-1)!];
	// Drop mappings the deletion left empty.
	for (let i = parents.length - 1; i > 0; i--) {
		if (Object.keys(parents[i]).length > 0) break;
		delete parents[i - 1][parts[i - 1]];
	}
}

/** The config.yml content for `profile`, keeping unmanaged settings from `existing`. */
export function buildConfig(existing: Tree, profile: Profile): Tree {
	const kept = structuredClone(existing);
	for (const id of RETIRED_KEYS) deletePath(kept, id);
	const managed = merge(readYaml(join(ROOT, "config/common.yml")), readYaml(join(ROOT, `config/${profile}.yml`)));
	return merge(kept, managed);
}

function agentDir(): string {
	return resolve(process.env.PI_CODING_AGENT_DIR || join(homedir(), ".omp/agent"));
}

function timestamp(): string {
	return new Date().toISOString().replace(/[-:]/g, "");
}

interface Manifest {
	profile: Profile;
	/** Files that existed before the install; their old copies are in the backup directory. */
	replaced: string[];
	/** Files the install created; restore deletes them. */
	created: string[];
}

function install(profile: Profile, dryRun: boolean): void {
	const dest = agentDir();
	const configText =
		`# Generated by omp-config install.ts (profile: ${profile}). Settings not managed by\n` +
		`# omp-config are kept on reinstall; edit config/*.yml in the repository for the rest.\n` +
		Bun.YAML.stringify(buildConfig(readYaml(join(dest, "config.yml")), profile), null, 2).replace(/[ \t]+$/gm, "") +
		"\n";
	const writes: Record<string, string> = {
		"config.yml": configText,
		"AGENTS.md": readFileSync(join(ROOT, "AGENTS.md"), "utf8"),
	};
	for (const p of PROFILES) writes[`profiles/${p}.yml`] = readFileSync(join(ROOT, `config/${p}.yml`), "utf8");
	const removals = RETIRED_FILES.filter(f => existsSync(join(dest, f)));

	if (dryRun) {
		console.log(`Destination: ${dest}\nProfile: ${profile}\nWrite: ${Object.keys(writes).join(", ")}`);
		if (removals.length) console.log(`Remove (after backup): ${removals.join(", ")}`);
		console.log(`\n--- config.yml ---\n${configText}`);
		return;
	}

	const backup = join(dest, "omp-config-backups", timestamp());
	if (existsSync(backup)) throw new Error(`backup directory already exists: ${backup}`);
	const manifest: Manifest = { profile, replaced: [], created: [] };
	for (const rel of [...Object.keys(writes), ...removals]) {
		const target = join(dest, rel);
		if (existsSync(target)) {
			mkdirSync(dirname(join(backup, rel)), { recursive: true });
			copyFileSync(target, join(backup, rel));
			manifest.replaced.push(rel);
		} else {
			manifest.created.push(rel);
		}
	}
	mkdirSync(backup, { recursive: true });
	writeFileSync(join(backup, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);

	for (const [rel, content] of Object.entries(writes)) {
		mkdirSync(dirname(join(dest, rel)), { recursive: true });
		writeFileSync(join(dest, rel), content);
	}
	for (const rel of removals) rmSync(join(dest, rel));

	console.log(`Installed profile "${profile}" into ${dest}`);
	if (removals.length) console.log(`Removed retired files: ${removals.join(", ")}`);
	console.log(`Backup: ${backup}\nRollback: ${join(ROOT, "install.ts")} --restore ${backup}`);
}

function restore(backup: string): void {
	const dest = agentDir();
	const dir = resolve(backup);
	const manifest = JSON.parse(readFileSync(join(dir, "manifest.json"), "utf8")) as Manifest;
	for (const rel of manifest.replaced) {
		mkdirSync(dirname(join(dest, rel)), { recursive: true });
		copyFileSync(join(dir, rel), join(dest, rel));
	}
	for (const rel of manifest.created) rmSync(join(dest, rel), { force: true });
	console.log(`Restored ${manifest.replaced.length} file(s) and removed ${manifest.created.length} from ${dest}`);
}

function main(argv: string[]): number {
	const usage = "Usage: install.ts --profile claude|codex [--dry-run] | --restore <backup-dir>";
	if (argv[0] === "--restore" && argv.length === 2) {
		restore(argv[1]);
		return 0;
	}
	const dryRun = argv.includes("--dry-run");
	const rest = argv.filter(a => a !== "--dry-run");
	const profile = rest[0] === "--profile" && rest.length === 2 ? rest[1] : undefined;
	if (!profile || !PROFILES.includes(profile as Profile)) {
		console.error(usage);
		return 2;
	}
	install(profile as Profile, dryRun);
	return 0;
}

if (import.meta.main) process.exit(main(Bun.argv.slice(2)));
